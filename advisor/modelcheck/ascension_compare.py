"""Game vs simulator for ascension and mutagen (advisor/ASCENSION.md, "Model check").

Plays two simulated runs with advisor/sim/sim.py (premutagen rolled exactly as the game rolls it), hands
their hatchery and expansion purchases to ascension_check.js, which buys the same levels through the real
game code, and lays the game's numbers beside the simulator's for: premutagen per level and over the runs,
the ascension cost, the state after an ascension, unlock and respec prices, every mutant's effect on rates
and spells, and crystals.

Usage (from the repo root; needs `npm install` in advisor/modelcheck and node on PATH):
    python3 -I advisor/modelcheck/ascension_compare.py      # about 25 s; tables also go to advisor/modelcheck/out/ascension_compare.md
"""
import json, math, os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
OUT = os.path.join(HERE, 'out'); os.makedirs(OUT, exist_ok=True)
sys.path.insert(0, os.path.join(REPO, 'advisor', 'sim'))
import sim
SAVES = {'s14': os.path.join(REPO, 'advisor', 'sim', 'example_save_14h.json'),
         's20': os.path.join(REPO, 'advisor', 'sim', 'example_save_20h.json')}
AGE0 = {'s14': 52124, 's20': 72406}
POLICY = json.load(open(os.path.join(REPO, 'advisor', 'sim', 'policy.json')))
TMP = os.path.join(OUT, '_ascension_tmp_save.json')

def sim_load(which, edit=None):
    d = json.load(open(SAVES[which]))
    if edit: edit(d)
    json.dump(d, open(TMP, 'w'))
    os.environ['SAVE'] = TMP
    return sim.load()

# ---- 1. simulated runs whose purchases the game replays
sim.PREMUT = 'exact'
PLAN = {'unlock': ['mutatenexus', 'mutatefreq', 'mutateeach'], 'buy': {'mutantnexus': 1e5, 'mutantfreq': 1e5, 'mutanteach': 0.5}}
runs = {}
os.environ['SAVE'] = SAVES['s20']
s20, rows20, log20 = sim.run_cycles(dict(POLICY, age0=AGE0['s20'], ascend=[{'after': 0}]), 60, 24 * 7, plans=[PLAN], every=12 * 3600)
os.environ['SAVE'] = SAVES['s14']
s14, rows14, _ = sim.run_cycles(dict(POLICY, age0=AGE0['s14']), 60, 24 * 4, every=12 * 3600)
replays = []
def add_replay(name, save, events, restarted_ms=None, mutants=None):
    ev = [e for e in events if e[2] >= (40 if e[1] == 'hatchery' else 80)]
    replays.append({'name': name, 'save': save, 'restarted_ms': restarted_ms, 'mutants': mutants or {},
                    'buys': [[e[1], e[2]] for e in ev], '_ev': ev})
add_replay('14.5 h save, 4 days, no ascension', 's14', s14.upg_log)
add_replay('20.1 h save, run 1 until it ascends', 's20', [e for e in s20.upg_log if e[3] == 0])
add_replay('20.1 h save, run 2 after the simulated ascension', 's20', [e for e in s20.upg_log if e[3] == 1],
           restarted_ms=log20[0]['restarted_ms'], mutants={k: v for k, v in s20.mut.items() if v})
spec = os.path.join(OUT, 'ascension_replays.json')
json.dump({'replays': [{k: v for k, v in r.items() if k != '_ev'} for r in replays]}, open(spec, 'w'))

# ---- 2. the game
game = json.loads(subprocess.run(['node', os.path.join(HERE, 'ascension_check.js'), spec], check=True,
                                 capture_output=True, text=True, env=dict(os.environ, TZ='UTC')).stdout)

lines = []
def out(x=''): lines.append(x); print(x)
def fmt(x):
    if x is None: return '-'
    if isinstance(x, bool): return str(x)
    if x == 0: return '0'
    if abs(x) >= 1e5 or abs(x) < 1e-2: return '%.6g' % x
    return ('%.6f' % x).rstrip('0').rstrip('.')
def ratio(sv, gv):
    if gv == 0 and sv == 0: return '1'
    if gv == 0: return 'inf'
    r = sv / gv
    return '%.7f' % r if abs(r - 1) < 1e-3 else '%.4g' % r
WORST = []
def row(name, gv, sv, note=''):
    gv = float(gv); sv = float(sv)
    if gv or sv: WORST.append((abs(sv / gv - 1) if gv else float('inf'), name))
    out('| %s | %s | %s | %s |%s' % (name, fmt(gv), fmt(sv), ratio(sv, gv), (' ' + note + ' |') if note else ''))
def head(title, cols=('quantity', 'game', 'sim', 'sim/game')):
    out(); out('### ' + title); out(); out('| ' + ' | '.join(cols) + ' |'); out('|' + ' --- |' * len(cols))

out('# Ascension and mutagen: game vs simulator'); out()
out('Generated by `advisor/modelcheck/ascension_compare.py`; game time zone %s (the game seeds its rolls with the start date in local time).' % game['tz'])

# premutagen per level
head('Premutagen roll per level (effect output, both saves)', ('save / upgrade', 'levels', 'spawn flag equal', 'quantity equal', 'largest |sim/game - 1|'))
for w in ('s14', 's20'):
    s = sim_load(w)
    for up, lv in game['levels'][w].items():
        n = same_sp = same_q = 0; worst = 0.0
        for L, (sp, q, base) in lv.items():
            L = int(L); ssp, sq = sim.premut_roll(s, up, L, 'exact', raw=True); n += 1
            same_sp += (ssp == sp); q = float(q)
            if ssp == sp and (q == sq or (q and abs(sq / q - 1) < 1e-12)): same_q += 1
            if q: worst = max(worst, abs(sq / q - 1))
            WORST.append((abs(sq / q - 1) if q else (0 if sq == 0 else float('inf')), 'roll %s %s %d' % (w, up, L)))
        out('| %s %s | %d | %d | %d | %.2g |' % (w, up, n, same_sp, same_q, worst))
# expected value per level
s = sim_load('s20')
out(); out('Expected premutagen per level (sim, `expected` mode) = each x factor^level x P(spawn); P = 1 at the first level and every 8th, else freq. At the 20 h save: hatchery 40: %s, 41: %s; expansion 80: %s, 81: %s, 200: %s.' % tuple(
    fmt(sim.premut_roll(s, u, L, 'expected')[1]) for u, L in [('hatchery', 40), ('hatchery', 41), ('expansion', 80), ('expansion', 81), ('expansion', 200)]))

# real buys
head('Premutagen from real purchases (20 h save, hatchery 33-60, expansion 66-120)', ('case', 'purchases', 'premutagen, game', 'premutagen, sim', 'sim/game', 'freq game / sim', 'each game / sim'))
for case, mut in [('plain', {}), ('mutants', {'mutanteach': 1e6, 'mutantfreq': 1e4})]:
    g = game['buys'][case]; s = sim_load('s20')
    for k, v in mut.items(): s.mut[k] = v
    sim.refresh_mut(s)
    gt = sum(float(x[2]) for x in g['steps']); st = sum(sim.premut_roll(s, x[0], x[1], 'exact')[1] for x in g['steps'])
    for x in g['steps']:
        sq = sim.premut_roll(s, x[0], x[1], 'exact')[1]; q = float(x[2])
        WORST.append((abs(sq / q - 1) if q else (0 if sq == 0 else float('inf')), 'buy %s %s %d' % (case, x[0], x[1])))
    out('| %s | %d | %s | %s | %s | %s / %s | %s / %s |' % (case, len(g['steps']), fmt(gt), fmt(st), ratio(st, gt), fmt(float(g['freq'])), fmt(s.freq), fmt(float(g['each'])), fmt(s.each)))

# replays
for rp, grp in zip(replays, game['replays']):
    head('Premutagen over a simulated run: ' + rp['name'], ('purchase # (sim time)', 'hatchery / expansion level', 'game', 'sim (exact)', 'sim/game', 'sim (expected)'))
    ev = rp['_ev']; cum = 0.0; exp_cum = 0.0
    s = sim_load(rp['save'])
    if rp['restarted_ms'] is not None: s.restarted_ms = rp['restarted_ms']
    for k, v in rp['mutants'].items(): s.mut[k] = v
    sim.refresh_mut(s)
    marks = sorted(set([len(ev) - 1] + [int(len(ev) * f) for f in (0.1, 0.25, 0.5, 0.75)]))
    hl = {'hatchery': 0, 'expansion': 0}
    for i, e in enumerate(ev):
        cum += e[4]; exp_cum += sim.premut_roll(s, e[1], e[2], 'expected')[1]; hl[e[1]] = e[2]
        gv = float(grp['premutagen'][i])
        WORST.append((abs(cum / gv - 1) if gv else (0 if cum == 0 else float('inf')), 'replay %s #%d' % (rp['name'], i)))
        if i in marks:
            out('| %d (%.1f h) | %d / %d | %s | %s | %s | %s |' % (i + 1, e[0] / 3600, hl['hatchery'], hl['expansion'], fmt(gv), fmt(cum), ratio(cum, gv), fmt(exp_cum)))

# ascension cost
head('Ascension cost (energy) on the 20 h save with edits', ('case', 'spent, game', 'spent, sim', 'cost, game', 'cost, sim', 'sim/game'))
for c in game['cost']:
    def ed(d, e=c['edit']):
        d['unittypes'].update(e.get('u', {})); d['upgrades'].update(e.get('g', {}))
    s = sim_load('s20', ed)
    sp, cs = sim.espent(s), sim.asc_cost(s)
    WORST.append((abs(cs / float(c['cost']) - 1), 'cost ' + c['name'])); WORST.append((abs(sp / float(c['spent']) - 1), 'spent ' + c['name']))
    out('| %s | %s | %s | %s | %s | %s |' % (c['name'], fmt(float(c['spent'])), fmt(sp), fmt(float(c['cost'])), fmt(cs), ratio(cs, float(c['cost']))))
    WORST.append((abs(math.ceil(0.3 * cs) / float(c['respecCost']) - 1), 'respec cost ' + c['name']))
    WORST.append((abs(sim.ecap(s) / float(c['cap']) - 1), 'cap ' + c['name']))

