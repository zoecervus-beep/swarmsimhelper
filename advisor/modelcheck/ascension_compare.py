simu = {'meat': s.c[0], 'larva': s.larva, 'mutagen': s.mutagen, 'premutagen': s.premut, 'ascension': s.asc, 'freeRespec': s.freerespec,
        'mtxEnergy': s.mtx, 'crystal': s.crystal, 'mutantfreq': s.mut['mutantfreq'], 'invisiblehatchery': 1, 'energy': s.energy,
        'nexus': s.nexus, 'territory': s.terr, 'drone': s.c[1], 'hive': s.c[5], 'moth': s.moth, 'swarmling': s.t[0]}
for k in sorted(set(a['after']['units']) | {'energy', 'nexus', 'territory', 'drone', 'hive', 'moth', 'premutagen'}):
    row('unit ' + k, a['after']['units'].get(k, 0), simu.get(k, float('nan')))
gup = a['after']['upgrades']
supg = {'mutatefreq': int('mutatefreq' in s.unlocked), 'hatchery': s.hatch, 'expansion': s.exp, 'achievementbonus': s.ach, 'droneprod': s.prod[1], 'dronetwin': s.twin[1], 'nexus4': int(s.nexus >= 4)}
for k in sorted(set(gup) | set(supg)): row('upgrade ' + k, gup.get(k, 0), supg.get(k, 0))
row('achievement points (ascension1 +10)', a['achAfter'], s.achpts)
row('larvae / s', a['larvaRate'], sim.lam(s))
row('energy cap', a['cap'], sim.ecap(s))
row('next ascension cost', a['costAfter'], sim.asc_cost(s))
row('restart time (ms)', a['restartedAfter'], a['now'], 'the game restarts the run clock at the moment of ascending')
out(); out('Statistics (units bought) survive: hive before `%s`, after `%s`.' % (a['statsBefore'], a['statsAfter']))
out('After 600 s the game holds %s larvae (10 + 600 x %s); meat stays %s (no drones).' % (a['after600']['larva'], a['larvaRate'], a['after600']['meat']))

head('Repeated ascensions with nothing spent', ('ascensions', 'cost, game', 'cost, sim', 'free respecs, game', 'free respecs, sim'))
for r in game['repeat']:
    n = int(r['ascensions']); s = sim_load('s20', lambda d, n=n: d['unittypes'].update({'ascension': str(n), 'moth': '0', 'nexus': '0'}) or d['upgrades'].update({'nexus2': '0', 'nexus3': '0', 'nexus4': '0'}))
    sc = sim.asc_cost(s); fr = 4 + n // 3
    WORST.append((abs(sc / float(r['cost']) - 1), 'repeat cost %d' % n))
    out('| %d | %s | %s | %s | %d |' % (n, r['cost'], fmt(sc), r['freeRespec'], fr))

u = game['unlocks']
