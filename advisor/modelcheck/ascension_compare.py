def gval(r, q):
    if q == 'larva/s': return r['larva']
    if q == 'spell power': return r['power']
    if q == 'energy/s': return r['energy']
    if q == 'energy cap': return r['cap']
    if q == 'ascension cost': return r['ascendCost']
    if q == 'premutagen quantity x': return r['each']
    if q == 'premutagen chance': return r['freq']
    if q.endswith('territory each'): return r['tprod'][q.split()[0]]
    if q.endswith('production each'): return r['prod'][q.split()[0]]
    sp = r.get('spells') or base['spells']
    return {'larva rush larvae': sp['larvarush'], 'territory rush': sp['territoryrush'], 'clone larvae gained (capped)': sp['clonelarvae'],
            'swarmwarp drones gained': sp['swarmwarpDrones']}[q]
