#!/usr/bin/env bash
# Idempotent dev-toolchain setup for this Swarm Simulator fork (Linux x64).
#
# Installs, outside the repo, into $SWARMSIM_TOOLCHAIN_DIR
# (default: ~/.cache/swarmsim-toolchain):
#   - Node 16.20.2 (the version upstream CI uses) + yarn 1.22.22,
#     unless `node` on PATH is already v16
#   - the `compass` Ruby gem (needed by `grunt build` / `grunt serve`),
#     plus a small shim when Ruby >= 3.2 (compass/sass call File.exists?,
#     which Ruby 3.2 removed)
#   - env.sh, which every new shell must source before using yarn/grunt/karma
# then runs `yarn install --frozen-lockfile` at the repo root. If
# codeload.github.com is unreachable it instead installs swarmsim-coffee via
# advisor/npm-bower-fallback.sh (npm-registry copies) and exits 3 when that
# fallback leaves gaps.
#
# Usage:  advisor/setup-dev.sh            (full setup)
#         advisor/setup-dev.sh --no-install   (toolchain + env.sh only)
#         advisor/setup-dev.sh --near-versions  (OPT-IN, fallback path only: also
#             install npm stand-ins that are NOT the pinned versions; see
#             advisor/npm-bower-fallback.sh)
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TC="${SWARMSIM_TOOLCHAIN_DIR:-${XDG_CACHE_HOME:-$HOME/.cache}/swarmsim-toolchain}"
NODE_VERSION=16.20.2
YARN_VERSION=1.22.22
DO_INSTALL=1
FALLBACK_ARGS=()
for a in "$@"; do
  case "$a" in
    --no-install) DO_INSTALL=0 ;;
    --near-versions) FALLBACK_ARGS+=(--near-versions) ;;
    *) echo "unknown argument: $a" >&2; exit 64 ;;
  esac
done
mkdir -p "$TC"
log() { printf '\n== %s\n' "$*"; }

# ---------------------------------------------------------------- Node 16
NODE_BIN=""
if command -v node >/dev/null 2>&1 && node -v | grep -q '^v16\.'; then
  NODE_BIN="$(dirname "$(command -v node)")"
  log "Using Node $(node -v) already on PATH ($NODE_BIN)"
else
  NODE_DIR="$TC/node-v$NODE_VERSION-linux-x64"
  if [ ! -x "$NODE_DIR/bin/node" ]; then
    log "Downloading Node $NODE_VERSION"
    tmp="$(mktemp -d "$TC/dl.XXXXXX")"
    f="node-v$NODE_VERSION-linux-x64.tar.xz"
    curl -fsSL -o "$tmp/$f" "https://nodejs.org/dist/v$NODE_VERSION/$f"
    curl -fsSL "https://nodejs.org/dist/v$NODE_VERSION/SHASUMS256.txt" | grep " $f\$" > "$tmp/sum"
    (cd "$tmp" && sha256sum -c sum)
    tar -xJf "$tmp/$f" -C "$TC"
    rm -rf "$tmp"
  fi
  NODE_BIN="$NODE_DIR/bin"
  export PATH="$NODE_BIN:$PATH"
  log "Node $(node -v) at $NODE_BIN"
fi
# Some sandboxes set NODE_OPTIONS=--use-openssl-ca; Node 16 rejects that flag
# in worker threads (breaks Parcel). NODE_EXTRA_CA_CERTS still applies.
NODE_OPTIONS="$(printf '%s' "${NODE_OPTIONS:-}" | sed 's/--use-openssl-ca//g; s/^ *//; s/ *$//')"
export NODE_OPTIONS
if ! command -v yarn >/dev/null 2>&1 || [ "$(yarn -v)" != "$YARN_VERSION" ]; then
  log "Installing yarn $YARN_VERSION into Node 16's global prefix"
  "$NODE_BIN/npm" install -g "yarn@$YARN_VERSION" >/dev/null
fi
log "yarn $(yarn -v) at $(command -v yarn)"

# ---------------------------------------------------------------- compass
command -v ruby >/dev/null 2>&1 || { echo "ruby not found; install Ruby (any 2.5+)" >&2; exit 1; }
export GEM_HOME="$TC/gems" GEM_PATH="$TC/gems"
export PATH="$GEM_HOME/bin:$PATH"
RUBYOPT_LINE=""
if ruby -e 'exit(Gem::Version.new(RUBY_VERSION) >= Gem::Version.new("3.2") ? 0 : 1)'; then
  cat > "$TC/ruby32-file-exists-compat.rb" <<'EOF'
# compass 1.0.3 / sass 3.4 use File.exists? and Dir.exists?, removed in Ruby 3.2.
class File; class << self; alias_method :exists?, :exist? unless method_defined?(:exists?); end; end
class Dir;  class << self; alias_method :exists?, :exist? unless method_defined?(:exists?); end; end
EOF
  export RUBYOPT="-r$TC/ruby32-file-exists-compat.rb"
  RUBYOPT_LINE="export RUBYOPT=\"-r$TC/ruby32-file-exists-compat.rb\""
fi
if ! [ -x "$GEM_HOME/bin/compass" ]; then
  log "Installing compass gem into $GEM_HOME"
  gem install compass --no-document
fi
log "$(compass --version | head -1) on $(ruby -v)"

# ---------------------------------------------------------------- env.sh
CHROME_GUESS="${CHROME_BIN:-}"
if [ -z "$CHROME_GUESS" ]; then
  CHROME_GUESS="$(ls -d /opt/pw-browsers/chromium-*/chrome-linux64/chrome 2>/dev/null | sort | tail -1 || true)"
fi
cat > "$TC/env.sh" <<EOF
# Generated by advisor/setup-dev.sh. Source in every shell:  . "$TC/env.sh"
export PATH="$NODE_BIN:\$PATH"
export GEM_HOME="$GEM_HOME" GEM_PATH="$GEM_HOME"
export PATH="$GEM_HOME/bin:\$PATH"
$RUBYOPT_LINE
# Node 16 workers reject --use-openssl-ca (set by some sandboxes).
export NODE_OPTIONS="\$(printf '%s' "\${NODE_OPTIONS:-}" | sed 's/--use-openssl-ca//g; s/^ *//; s/ *\$//')"
# PhantomJS 2.1.1 (Karma's browser) aborts reading modern openssl.cnf files.
export OPENSSL_CONF=/dev/null
${CHROME_GUESS:+export CHROME_BIN="\${CHROME_BIN:-$CHROME_GUESS}"}
EOF
log "Wrote $TC/env.sh"

[ "$DO_INSTALL" = 1 ] || exit 0

# ---------------------------------------------------------------- yarn install
# swarmsim-coffee's bower deps are GitHub tarballs (codeload.github.com).
probe="https://codeload.github.com/angular/bower-angular/tar.gz/3828060389c83384b0a162eea82b21f183aa060c"
code="$(curl -sS -o /dev/null -w '%{http_code}' "$probe" || true)"
cd "$REPO"
if [ "$code" = "200" ]; then
  log "yarn install --frozen-lockfile (root + tables + swarmsim-ts + swarmsim-coffee)"
  yarn install --frozen-lockfile
  log "Done. In each new shell:  . \"$TC/env.sh\""
  exit 0
fi

# FALLBACK: GitHub tarballs unreachable. Do what the root `install` script does,
# but install swarmsim-coffee through advisor/npm-bower-fallback.sh.
echo "WARNING: GitHub tarball download returned HTTP $code ($probe)." >&2
echo "Using the npm-registry fallback for swarmsim-coffee (advisor/npm-bower-fallback.sh)." >&2
log "yarn install (root, scripts off) + yarn link + tables + swarmsim-ts"
yarn install --frozen-lockfile --ignore-scripts
yarn run install:link
(cd tables && yarn install --frozen-lockfile)
(cd swarmsim-ts && yarn install --frozen-lockfile)
"$REPO/advisor/npm-bower-fallback.sh" ${FALLBACK_ARGS[@]+"${FALLBACK_ARGS[@]}"}
echo >&2
echo "Installed WITH GAPS: some GitHub-pinned libraries have no npm copy (listed above)." >&2
echo "In each new shell:  . \"$TC/env.sh\"" >&2
exit 3
